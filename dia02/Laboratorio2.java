package dia03;

public class Laboratorio2 {
    public static void main(String[] args) {
        System.out.println(9 / 4); // resultado esperado: 2.25 ou somente 2 se for inteiro
        System.out.println(9.0 / 4); // resultado esperado: 2.25
        System.out.println("Vlan " + 10 + 20); // resultado esperado: Vlan 1020
        System.out.println("Total: " + 10 * 3); // resultado esperado: Total: 30
        System.out.println('Z' + 0); // resultado esperado: posicao de Z + 0
        System.out.println("Z" + 0); // resultado esperado Z0
        System.out.println("Portas: " + (10 + 20)); // resultado esperado: Portas: 30
    }
}

